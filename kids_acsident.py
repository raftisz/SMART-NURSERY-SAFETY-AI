def analyze_and_detect(frame):
    global last_alert_time

    # เพิ่ม conf และ iou (NMS) เพื่อตัดกล่องซ้อนมั่ว
    results = model(frame, conf=0.30, iou=0.45, verbose=False)

    is_danger = False
    alert_msg = ""

    h_img, w_img, _ = frame.shape

    for r in results:
        # วาดกล่อง Pose / Bounding Box พื้นฐาน
        frame = r.plot()

        # ---------------------------------------------------------------------
        # 1. ตรวจจับโดยใช้ Bounding Box (ทำงานชัวร์ 100% แม้ Keypoints จะหลุด)
        # ---------------------------------------------------------------------
        if r.boxes is not None and len(r.boxes) > 0:
            boxes = r.boxes.xyxy.cpu().numpy() # [x1, y1, x2, y2]
            clfs = r.boxes.conf.cpu().numpy()

            for idx, (box, conf) in enumerate(zip(boxes, clfs)):
                x1, y1, x2, y2 = box
                box_h = y2 - y1
                box_w = x2 - x1

                # เช็กตำแหน่งส่วนบนสุดของกล่อง (y1) และตำแหน่งกึ่งกลางแนวตั้ง
                center_y = (y1 + y2) / 2.0

                # เงื่อนไขการปีนป่าย:
                # 1. ตัวเด็กอยู่โซนกลาง-บนของภาพ (y1 อยู่ครึ่งบนของจอ)
                # 2. หรือกล่องมีความสูงยืดขนานกับโต๊ะ
                is_climbing_box = (y1 < h_img * 0.6)

                # ---------------------------------------------------------------------
                # 2. ตรวจจับร่วมกับ Keypoints (ถ้ามี)
                # ---------------------------------------------------------------------
                is_climbing_kpt = False
                if r.keypoints is not None and len(r.keypoints.data) > idx:
                    kpts = r.keypoints.data[idx].cpu().numpy()
                    if len(kpts) >= 17:
                        # ดึงค่าจุดที่มี confidence เกิน 0.1
                        valid_y = [kpt[1] for kpt in kpts if kpt[2] > 0.1]
                        if len(valid_y) > 0:
                            min_y = min(valid_y)
                            if min_y < h_img * 0.65:
                                is_climbing_kpt = True

                # ---------------------------------------------------------------------
                # สรุปผลสถานะการแจ้งเตือน
                # ---------------------------------------------------------------------
                if is_climbing_box or is_climbing_kpt:
                    status = "DANGER: CLIMBING DETECTED!"
                    color = (0, 0, 255) # สีแดงสด (BGR)
                    is_danger = True
                    alert_msg = f"⚠️ [แจ้งเตือนภัยด่วน!] ตรวจพบเด็กคนที่ #{idx+1} มีพฤติกรรมเสี่ยงปีนป่ายโต๊ะ/เก้าอี้!"
                else:
                    status = "NORMAL"
                    color = (0, 255, 0) # สีเขียว

                # ---------------------------------------------------------------------
                # 3. วาดแถบข้อความเตือนภัยสีแดงบนภาพ (ให้เห็นชัดเจนแน่นอน)
                # ---------------------------------------------------------------------
                # สร้างแถบพื้นหลังสีดำขอบสีแดง/เขียว ด้านบนภาพ
                top_offset = 20 + (idx * 55)
                cv2.rectangle(frame, (15, top_offset), (615, top_offset + 45), (0, 0, 0), -1)
                cv2.rectangle(frame, (15, top_offset), (615, top_offset + 45), color, 3)
                cv2.putText(frame, f"Child #{idx+1}: {status}",
                            (25, top_offset + 32), cv2.FONT_HERSHEY_SIMPLEX,
                            0.75, color, 2, cv2.LINE_AA)

    # -------------------------------------------------------------------------
    # 4. แสดงแถบคาดเตือนภัยสีแดงด้านล่างจอ + ส่ง LINE Alert
    # -------------------------------------------------------------------------
    if is_danger:
        # แถบแดงคาดล่างจอ
        cv2.rectangle(frame, (0, h_img - 50), (w_img, h_img), (0, 0, 255), -1)
        cv2.putText(frame, "⚠️ WARNING: CHILD CLIMBING / RISK DETECTED!",
                    (25, h_img - 15), cv2.FONT_HERSHEY_SIMPLEX,
                    0.7, (255, 255, 255), 2, cv2.LINE_AA)

        # ส่งข้อความเข้า LINE (เว้นระยะ cooldown 10 วินาที)
        current_time = time.time()
        if current_time - last_alert_time > ALERT_COOLDOWN:
            send_line_message_text(alert_msg)
            last_alert_time = current_time

    return frame

