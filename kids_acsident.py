def get_frame():
    js = Javascript('''
    (async () => {
      if (!window.webcamStream) return null;
      const { video, canvas, ctx } = window.webcamStream;
      ctx.drawImage(video, 0, 0, 640, 480);
      return canvas.toDataURL('image/jpeg', 0.6); // ย่อคุณภาพเหลือ 0.6 เพื่อความเร็ว
    })()
    ''')
    data_url = eval_js(js)
    if not data_url: return None
    header, encoded = data_url.split(",", 1)
    data = base64.b64decode(encoded)
    np_arr = np.frombuffer(data, np.uint8)
    return cv2.imdecode(np_arr, cv2.IMREAD_COLOR)

